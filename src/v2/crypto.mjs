export function structHash(type, obj, types=TYPES) {
 const fields = types[type]; if (!fields) throw Error('unknown type');
 const encode = (t,v) => {
  if (types[t]) return structHash(t,v,types);
  if (t==='string') return keccak_256(utf8(v));
  if (t==='uint256') { const n=BigInt(v); if(n<0n || n>=2n**256n) throw Error('uint'); return unhex('0x'+n.toString(16).padStart(64,'0')); }
  const b=unhex(v); if (t==='bytes32' && b.length===32) return b;
  if (t==='address' && b.length===20) return Buffer.concat([Buffer.alloc(12),b]);
  throw Error('type/length');
 };
 const declaration=t=>t+'('+types[t].map(([n,k])=>k+' '+n).join(',')+')';
 const dependencies=new Set();
 const visit=t=>{for(const [,k] of types[t]) if(types[k] && k!==type && !dependencies.has(k)){dependencies.add(k);visit(k);}};
 visit(type);
 const typeText=declaration(type)+[...dependencies].sort().map(declaration).join('');
 return keccak_256(Buffer.concat([keccak_256(utf8(typeText)), ...fields.map(([n,t])=>encode(t,obj[n]))]));
}
export function digest(doc, types=TYPES) { return keccak_256(Buffer.concat([Buffer.from([25,1]), structHash('EIP712Domain',doc.domain,types),structHash(doc.type,doc.message,types)])); }
export function address(publicKey) { return hex(keccak_256(secp256k1.Point.fromBytes(publicKey).toBytes(false).slice(1)).slice(-20)); }
export function sign(type, message, key, domain) {
 const doc={type,domain,message}; const sig=secp256k1.sign(digest(doc), key, {prehash:false,format:'recovered'});
 return {...doc, signature:hex(Buffer.concat([sig.slice(1),Buffer.from([sig[0]+27])])), signer:address(secp256k1.getPublicKey(key))};
}
export function verify(doc) {
 if (!doc) return {status:'UNVERIFIABLE', reason:'missing signature artifact'};
 if (!Object.hasOwn(TYPES,doc.type) || doc.type==='EIP712Domain') return {status:'UNVERIFIABLE',reason:'unsupported signed artifact schema'};
 try {
  const s=unhex(doc.signature); if(s.length!==65 || ![27,28].includes(s[64])) return {status:'REFUTED',reason:'invalid signature encoding'};
  const recovered=Buffer.concat([Buffer.from([s[64]-27]),s.slice(0,64)]);
  const pk=secp256k1.recoverPublicKey(recovered,digest(doc),{prehash:false});
  const valid=secp256k1.verify(s.slice(0,64),digest(doc),pk,{prehash:false,lowS:true}) && address(pk)===doc.signer;
  return {status:valid?'VERIFIED':'REFUTED',signer:address(pk),digest:hex(digest(doc))};
 } catch { return {status:'REFUTED',reason:'signature verification rejected'}; }
}
